#!/usr/bin/env python3
"""Generates Source/SvdTables.h from the field tables in svdtool.py (snd909.svd layout,
verified on hardware). Usage: gen_svd_tables.py path/to/svdtool.py > Source/SvdTables.h"""
import sys, importlib.util
spec = importlib.util.spec_from_file_location('svdtool', sys.argv[1]); s = importlib.util.module_from_spec(spec); spec.loader.exec_module(s)
NIB = {'tone_delay_time': 2, 'wave_group_id': 4, 'wave_number_l': 4, 'wave_number_r': 4,
       'lfo1_rate': 2, 'lfo2_rate': 2, 'reserve_1f_20': 2}
def rows(tbl, base):
    off = 0; out = []
    for (n, pos, w, bias, lo, hi) in tbl:
        nb = NIB.get(n, 1)
        out.append((n, off, base + pos, w, nb, bias)); off += nb
    return out, off
sec = [('kCommon', rows(s.COMMON, 0)), ('kTMT', rows(s.TMT, s.TMT_START)), ('kTone', rows(s.TONE, s.TONE_START))]
print('// GENERATED by tools/gen_svd_tables.py from svdtool.py - do not edit by hand.')
print('// One row per Roland SysEx table row group: byte offset in the block, bit position in the')
print('// 598-byte patch item (tone 1 for kTone; add kToneStride per tone), bit width, SysEx nibble count, bias.')
print('#pragma once\n#include <cstdint>\nnamespace svd\n{')
print('struct Field { const char* name; uint16_t offset; uint16_t bit; uint8_t width; uint8_t nibbles; int16_t bias; };')
print(f'constexpr int kPatOffset = {s.PAT_OFF}, kItemBytes = {s.ITEM}, kNumSlots = 256, kToneStride = {s.STRIDE};')
for name, (r, size) in sec:
    print(f'constexpr int {name}Bytes = {size};')
    print(f'constexpr Field {name}Fields[] = {{')
    for (n, off, bit, w, nb, bias) in r:
        print(f'    {{ "{n}", {off}, {bit}, {w}, {nb}, {bias} }},')
    print('};')
    print(f'constexpr int {name}Count = {len(r)};')
print('}')
